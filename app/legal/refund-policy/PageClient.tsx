const policySections = policyText
  .trim()
  .split(/\n+/)
  .map(line => line.trim())
  .filter(Boolean)
  .reduce<Array<{ id: string; number: string; title: string; content: string[] }>>((sections, line) => {
    const match = line.match(/^(\d+)\.\s+(.+)$/);
    if (match) {
      const [, number, title] = match;
      sections.push({
        id: title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""),
        number,
        title,
        content: [],
      });
    } else {
      sections[sections.length - 1]?.content.push(line);
    }
    return sections;
  }, []);

const isListItem = (sectionTitle: string, line: string, index: number, content: string[]) => {
  if (!listSectionTitles.has(sectionTitle)) return false;
  const previousLine = content[index - 1] ?? "";
  const nextLine = content[index + 1] ?? "";
  return (
    previousLine.endsWith(":") ||
    previousLine.endsWith("; and") ||
    previousLine.endsWith("; or") ||
    line.endsWith(";") ||
    line.endsWith("; and") ||
    line.endsWith("; or") ||
    nextLine.endsWith(";") ||
    nextLine.endsWith("; and") ||
    nextLine.endsWith("; or")
  );
};

